package org.primefaces.integrationtests.datatable;

import java.io.Serializable;
import java.util.ArrayList;
import java.util.List;
import java.util.stream.Collectors;
import java.util.stream.IntStream;

import jakarta.annotation.PostConstruct;
import jakarta.faces.context.FacesContext;
import jakarta.faces.view.ViewScoped;
import jakarta.inject.Named;

import lombok.Data;

@Named
@ViewScoped
@Data
public class DataTable058 implements Serializable {

    private static final long serialVersionUID = 1L;

    private List<Integer> rows;
    private List<Integer> selection = new ArrayList<>();

    @PostConstruct
    public void init() {
        String requested = FacesContext.getCurrentInstance().getExternalContext().getRequestParameterMap().get("rows");
        int count = requested == null ? 100 : Math.max(1, Math.min(2000, Integer.parseInt(requested)));
        rows = IntStream.range(0, count).boxed().collect(Collectors.toList());
    }
}
